/**
 * Exercise glyph contact sheet (docs/exercise-glyphs.html): every glyph key at real tile size (44 px tile / 24 px mark)
 * in the light and dark themes, a large copy for detail, and the exercises that use it. Generated from the live glyph
 * code by tests/unit/exerciseGlyphs.test.tsx; regenerate with `npm run glyphs:sheet` (PNG: `npm run glyphs:png`).
 */
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ExerciseGlyph } from '@/components/ExerciseGlyph';
import { EXERCISES } from '@/data/exercises';
import { EXERCISE_GLYPHS, FALLBACK_GLYPH_KEYS, GLYPH_KEYS, PATTERN_GLYPHS, type GlyphKey } from '@/data/exerciseGlyphs';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function glyphUsage(): Map<GlyphKey, { exercises: string[]; patterns: string[] }> {
  const usage = new Map<GlyphKey, { exercises: string[]; patterns: string[] }>(GLYPH_KEYS.map((k) => [k, { exercises: [], patterns: [] }]));
  for (const ex of EXERCISES) usage.get(EXERCISE_GLYPHS[ex.id])?.exercises.push(ex.name);
  for (const [pattern, key] of Object.entries(PATTERN_GLYPHS)) usage.get(key)!.patterns.push(pattern);
  return usage;
}

export function renderGlyphContactSheet(): string {
  const usage = glyphUsage();
  const glyph = (key: GlyphKey, cls: string) => renderToStaticMarkup(createElement(ExerciseGlyph, { glyph: key, className: cls }));
  const cells = GLYPH_KEYS.map((key) => {
    const u = usage.get(key)!;
    const kept = (FALLBACK_GLYPH_KEYS as readonly string[]).includes(key);
    const notes = [
      u.exercises.length ? esc(u.exercises.join(' · ')) : '',
      u.patterns.length ? `<em>pattern fallback: ${u.patterns.join(', ')}</em>` : '',
      kept && !u.patterns.length ? '<em>last-resort fallback</em>' : '',
    ].filter(Boolean);
    return `<figure class="cell" id="${key}">
  <div class="big">${glyph(key, 'g96')}</div>
  <div class="tiles"><span class="tile light">${glyph(key, 'g24')}</span><span class="tile dark">${glyph(key, 'g24')}</span></div>
  <figcaption><code>${key}</code><span>${notes.join('<br>')}</span></figcaption>
</figure>`;
  }).join('\n');
  return `<!doctype html>
<!-- Generated by tests/unit/exerciseGlyphs.test.tsx (npm run glyphs:sheet). Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Exercise glyphs</title>
<style>
  :root { --bg: #f3efe7; --surface: #ffffff; --text: #17191b; --muted: #50595e; --accent: #a93623; }
  * { box-sizing: border-box; }
  body { margin: 0; padding: 24px 16px; background: var(--bg); color: var(--text); font: 13px/1.35 system-ui, sans-serif; }
  h1 { font-size: 20px; margin: 0 0 4px; }
  p.lede { margin: 0 0 20px; color: var(--muted); }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(220px, 1fr)); gap: 12px; }
  .cell { margin: 0; padding: 12px; background: var(--surface); border-radius: 14px; display: grid; grid-template-columns: 96px 1fr; gap: 8px 12px; align-items: start; }
  .big { color: var(--text); grid-row: span 2; }
  .g96 { width: 96px; height: 96px; display: block; }
  .g24 { width: 24px; height: 24px; display: block; }
  .tiles { display: flex; gap: 6px; }
  .tile { width: 44px; height: 44px; border-radius: 12px; display: inline-flex; align-items: center; justify-content: center; }
  .tile.light { background: #e6e2db; color: #a93623; }
  .tile.dark { background: #2a2e31; color: #ff806b; }
  figcaption { grid-column: 1 / -1; display: flex; flex-direction: column; gap: 2px; }
  code { font-weight: 600; font-size: 13px; }
  figcaption span { color: var(--muted); font-size: 12px; }
</style>
</head>
<body>
<h1>Exercise glyphs (${GLYPH_KEYS.length} keys)</h1>
<p class="lede">Direction B, 24×24, stroke 1.75, currentColor. Each card: 96 px preview, then the real 44 px list tile in the light and dark theme, the key, and the library exercises that use it.</p>
<div class="grid">
${cells}
</div>
</body>
</html>
`;
}
