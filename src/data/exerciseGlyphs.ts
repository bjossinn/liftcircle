export function isGlyphKey(key: unknown): key is GlyphKey {
  return typeof key === 'string' && (GLYPH_KEYS as readonly string[]).includes(key);
}

export function patternGlyphKey(pattern: MovementPattern | undefined): GlyphKey {
  return (pattern && PATTERN_GLYPHS[pattern]) || 'neutral';
}

/** Explicit key for library exercises, then the movement-pattern glyph (custom/unknown), then the neutral mark. */
export function exerciseGlyphKey(ex: Pick<Exercise, 'id' | 'pattern'> & { custom?: boolean }): GlyphKey {
  if (!ex.custom && Object.prototype.hasOwnProperty.call(EXERCISE_GLYPHS, ex.id)) return EXERCISE_GLYPHS[ex.id];
  return patternGlyphKey(ex.pattern);
}
